def _ledger(key, delta):
    """Atomically add delta to today's per-lane proposal count. Returns False
    (and changes nothing) when a +1 would pass the cap."""
    import fcntl
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    ledger = STATE_DIR / "proposals.json"
    with open(STATE_DIR / "proposals.lock", "a") as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        try:
            led = json.loads(ledger.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            led = {}
        day = key.split(":", 1)[0]
        led = {k: v for k, v in led.items() if k.startswith(day)}
        n = led.get(key, 0)
        if delta > 0 and n >= PROPOSALS_PER_LANE_PER_DAY:
            return False
        led[key] = max(0, n + delta)
        _write_if_changed(ledger, json.dumps(led))
        return True


def propose(lane, hook, rule, why=None, how=None):
    """A model's candidate memory. Slug is derived, never caller-chosen, so a
    proposal can never overwrite an existing memory. Quarantined until promoted."""
    hook, rule = (hook or "").strip(), (rule or "").strip()
    if not hook or not rule:
        return {"ok": False, "error": "hook and rule are both required"}
    if len(hook) > 140 or len(rule) > 2000:
        return {"ok": False, "error": "hook must be <=140 chars and rule <=2000"}
    blob = " ".join([hook, rule, why or "", how or ""])
    if SECRET_RX.search(blob):
        return {"ok": False, "error": "refused: the text looks like it holds a secret or code"}
    _, pats = _terms()
    if any(p.search(blob) for p in pats):
        return {"ok": False, "error": "refused: client-identifying text never goes into memory"}
    lane = re.sub(r"[^a-z0-9-]", "", (lane or "default").lower())[:20] or "default"
    slug = f"proposed-{lane}-{hashlib.sha256(rule.encode()).hexdigest()[:10]}"
    store = M.harness_store() or M.store_dir()
    if (store / f"{slug}.md").exists():
        return {"ok": True, "slug": slug, "note": "already proposed"}
    cmd = [sys.executable, str(DOOR), "write", "--slug", slug, "--type", "feedback",
           "--lineage", "contains-untrusted", "--description", hook, "--rule", rule,
           "--why", why or f"Proposed by the {lane} lane through the memory bridge; not yet reviewed.",
           "--how", how or "Served only after Craig promotes it (learn_card.py / sign.py --promote).",
           "--hook", hook, "--session-id", f"bridge-{lane}", "--commit", "--no-push"]
    key = f"{time.strftime('%Y-%m-%d')}:{lane}"
    if not _ledger(key, +1):            # reserve a slot under a lock: no cap race
        return {"ok": False, "error": f"daily proposal cap ({PROPOSALS_PER_LANE_PER_DAY}) reached for lane {lane}"}
    if os.environ.get("MESH_BRIDGE_DRY_PROPOSE"):
        _ledger(key, -1)
        return {"ok": True, "slug": slug, "dry_run": cmd}
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=120, cwd=str(HERE.parent))
    except Exception as e:  # noqa: BLE001
        _ledger(key, -1)
        return {"ok": False, "error": f"door failed: {e.__class__.__name__}: {e}"}
    if r.returncode != 0:
        _ledger(key, -1)
        return {"ok": False, "error": (r.stderr or r.stdout or "door refused").strip()[-400:]}
    return {"ok": True, "slug": slug, "status": "quarantined until Craig promotes it"}


