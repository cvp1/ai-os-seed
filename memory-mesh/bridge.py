SHELL_TOOLS = {"bash", "run_terminal_command", "shell", "exec_command", "local_shell",
               "execute_command", "terminal", "run_shell_command", "container.exec"}
FILE_TOOLS = {"write", "edit", "multiedit", "notebookedit", "search_replace", "hashline_edit",
              "write_file", "create_file", "edit_file", "strreplace", "str_replace_editor",
              "patch", "apply_patch", "editnotebook", "replace", "write_to_file",
              "delete_file", "move_file", "rename_file", "copy_file"}
READ_TOOLS = {"read", "read_file", "view", "grep", "glob", "list", "list_dir", "ls", "find",
              "search", "codebase_search", "web_search", "websearch", "web_fetch", "webfetch",
              "fetch", "todoread", "lsp"}
SHELL_KEYS = ("command", "cmd", "script", "commandLine", "command_line")
PATH_KEYS = ("file_path", "filePath", "path", "file", "files", "target_file", "target_notebook",
             "notebook_path", "filename", "target", "destination", "dest", "new_path",
             "newPath", "old_path", "source", "to", "from", "paths")
PATCH_RX = re.compile(r"^\*\*\* (?:(?:Add|Update|Delete) File|Move to):?\s*(.+)$", re.M)
# Same write shapes as hooks/memory-write-guard.py, for the policy-file check.
WRITE_SHAPE = re.compile(
    r">|\btee\b|\bsed\s+-i\b|\bcp\b|\bmv\b|\brm\b|\btruncate\b|\bdd\b"
    r"|\bscp\b|\brsync\b|\binstall\b|\bln\b|\bunlink\b|\bshred\b|\bchmod\b"
    r"|open\([^)]*['\"][wax]|\bwrite_text\b|\bjq\b.*>|\bperl\s+-[a-z]*i")
