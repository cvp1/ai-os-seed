def _query_arg(args):
    q = " ".join(args.query or []).strip()
    if not q and not sys.stdin.isatty():
        raw = sys.stdin.read()
        try:
            ev = json.loads(raw)
            q = ev.get("prompt") or ev.get("query") or ev.get("user_prompt") or raw
        except ValueError:
            q = raw
    return q


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("recall")
    r.add_argument("query", nargs="*")
    r.add_argument("--lane", default="default")
    r.add_argument("-k", type=int, default=5)
    r.add_argument("--format", choices=["text", "json", "block"], default="text")
    r.add_argument("--with-text", action="store_true")
    g = sub.add_parser("get")
    g.add_argument("id")
    g.add_argument("--lane", default="default")
    i = sub.add_parser("index")
    i.add_argument("--lane", default="default")
    p = sub.add_parser("propose")
    p.add_argument("--lane", default="default")
    p.add_argument("--hook", required=True)
    p.add_argument("--rule", required=True)
    p.add_argument("--why")
    p.add_argument("--how")
    rd = sub.add_parser("render")
    rd.add_argument("--quiet", action="store_true")
    gd = sub.add_parser("guard")
    gd.add_argument("--harness", default="generic")
    gd.add_argument("--policy-only", action="store_true",
                    help="check only the policy files (Claude Code guards the store itself)")
    hk = sub.add_parser("hook")
    hk.add_argument("name", choices=["claude-session"])
    for nm in ("install", "uninstall"):
        x = sub.add_parser(nm)
        x.add_argument("--apply", action="store_true")
        x.add_argument("--only", nargs="*")
    sub.add_parser("status")
    args = ap.parse_args(argv)

    if args.cmd == "recall":
        q = _query_arg(args)
        if args.format == "block":     # per-turn injection: same skip as the Claude hook
            words = re.findall(r"[a-z0-9][a-z0-9_-]{2,}", R.fence(q).lower())
            if len(words) < R.MIN_PROMPT_WORDS:
                q = ""
        hits = recall(q, args.lane, args.k, with_text=args.with_text) if q else []
        if args.format == "json":
            print(json.dumps({"lane": args.lane, "hits": hits}, indent=1))
        elif args.format == "block":
            if hits:
                print(R.render([(h["score"], h["id"], h["desc"]) for h in hits]))
        else:
            for h in hits:
                print(f"{h['score']:.2f}  [{h['id']}] {h['desc']}")
                if args.with_text and h.get("text"):
                    print("    " + h["text"].replace("\n", "\n    ")[:2000])
            if not hits:
                print("(no memories matched)")
        return 0
    if args.cmd == "get":
        d = get(args.id, args.lane)
        if not d:
            print(f"no servable memory {args.id!r}", file=sys.stderr)
            return 1
        print(d.get("text") or json.dumps(d))
        return 0
    if args.cmd == "index":
        sys.stdout.write(render_lane(args.lane))
        return 0
    if args.cmd == "propose":
        out = propose(args.lane, args.hook, args.rule, args.why, args.how)
        print(json.dumps(out, indent=1))
        return 0 if out.get("ok") else 1
    if args.cmd == "render":
        res = render_all(quiet=args.quiet)
        for a in res["alarms"]:
            print(a, file=sys.stderr)
        return 0
    if args.cmd == "guard":
        ok, why = guard(sys.stdin.read(), policy_only=args.policy_only)
        if not ok:
            print(why, file=sys.stderr)
            print(json.dumps({"decision": "block", "reason": why,
                              "hookSpecificOutput": {"hookEventName": "PreToolUse",
                                                     "permissionDecision": "deny",
                                                     "permissionDecisionReason": why}}))
            return 2
        return 0
    if args.cmd == "hook":
        out = hook_claude_session(sys.stdin.read() if not sys.stdin.isatty() else "{}")
        if out:
            print(out)
        return 0
    if args.cmd in ("install", "uninstall"):
        rep = install(apply=args.apply, undo=args.cmd == "uninstall", only=args.only)
        for name, state, detail in rep:
            print(f"{name:16} {state:12} {detail}")
        if not args.apply and any(s.startswith("would") for _, s, _ in rep):
            print(f"\n(dry run) re-run with --apply to make these changes; backups go to {BACKUP_DIR}")
        return 1 if any(s in ("FAILED", "ERROR") for _, s, _ in rep) else 0
    if args.cmd == "status":
        for name, typ, lane, state in status():
            print(f"{name:16} {typ:16} {lane:8} {state}")
        return 0
    return 2


if __name__ == "__main__":
    try:
        sys.exit(main())
    except BrokenPipeError:
        sys.exit(0)
