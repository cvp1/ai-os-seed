MAX_SCAN_STRINGS = 2000
GUARD_BUDGET_S = 6.0          # all store checks for one call; under the plugin's 8 s


def _forms(p):
    """A path as written and as resolved: commands name the first, the
    filesystem reports the second (macOS /var vs /private/var)."""
    p = os.path.abspath(os.path.expanduser(str(p)))
    return {p, os.path.realpath(p)}


def _store_paths():
    return sorted(_forms(os.environ.get("MEMORY_WRITE_GUARD_STORE") or str(M.store_dir())))


CODE_FILES = ("bridge.py", "mcp_server.py", "opencode_memory_plugin.mjs", "retrieve.py",
              "memory_write.py", "mesh_lib.py", "fold.py", "hooks")


def policy_paths(cfg=None, include_code=True):
    """Files whose edit would change what a lane may see: the bridge's own
    config dir, the repo config, the deny list, every harness file the bridge
    wires, and (for non-Claude harnesses) the memory code itself. Claude Code
    develops this code; its own edits stay with the operator's review."""
    out = _forms(CONF_DIR) | _forms(_learn_deny_file())
    if include_code:
        out |= _forms(DEFAULT_CONFIG)
        for name in CODE_FILES:
            out |= _forms(HERE / name)
    try:
        cfg = cfg or load_config()
        for t in (cfg.get("targets") or {}).values():
            # Instruction files (static_file) are not policy: the fold rewrites
            # their block every cycle and harnesses write their own text there.
            if isinstance(t, dict) and t.get("path") and t.get("type") != "static_file":
                out |= _forms(_x(t["path"]))
            for pp in (t.get("project_settings") or []) if isinstance(t, dict) else []:
                out |= _forms(_x(pp))
        if include_code:
            try:
                _write_if_changed(STATE_DIR / "policy-paths.json", json.dumps(sorted(out)))
            except OSError:
                pass
    except Exception:  # noqa: BLE001 — config unreadable: use the last known set
        try:
            out |= set(json.loads((STATE_DIR / "policy-paths.json").read_text(encoding="utf-8")))
        except (OSError, ValueError):
            pass
    return sorted(out)


def _under(path, roots):
    cands = _forms(path)
    return any(c == r or c.startswith(r.rstrip("/") + "/") for c in cands for r in roots)


def _mentions(text, roots):
    home = str(HOME)
    for r in roots:
        forms = {r, r.replace(home, "~", 1), r.replace(home, "$HOME", 1)}
        if any(f in text for f in forms):
            return True
    return False


def _strings(obj, depth=0, acc=None):
    acc = [] if acc is None else acc
    if len(acc) >= MAX_SCAN_STRINGS or depth > 6:
        return acc
    if isinstance(obj, str):
        acc.append(obj)
    elif isinstance(obj, dict):
        for v in obj.values():
            _strings(v, depth + 1, acc)
    elif isinstance(obj, (list, tuple)):
        for v in obj:
            _strings(v, depth + 1, acc)
    return acc


def _paths(obj, depth=0, acc=None):
    """Every value under a path-like key, at any depth (MultiEdit `edits`, `files` lists)."""
    acc = [] if acc is None else acc
    if depth > 6 or len(acc) >= MAX_SCAN_STRINGS:
        return acc
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k in PATH_KEYS:
                acc.extend(s for s in _strings(v) if s.strip())
            if isinstance(v, (dict, list)):
                _paths(v, depth + 1, acc)
    elif isinstance(obj, list):
        for v in obj:
            _paths(v, depth + 1, acc)
    return acc


def _tool_and_input(ev):
    tool = str(ev.get("tool_name") or ev.get("toolName") or ev.get("tool") or "")
    inp = ev.get("tool_input")
    if inp is None:
        inp = ev.get("toolInput")
    if inp is None:
        inp = ev.get("args")
    if inp is None:
        inp = ev.get("input")
    if isinstance(inp, str):
        inp = {"command": inp}
    return tool, (inp if isinstance(inp, (dict, list)) else {})


def normalize_event(ev):
    """Map any harness's PreToolUse event to Claude-shaped guard events."""
    tool, inp = _tool_and_input(ev)
    d = inp if isinstance(inp, dict) else {}
    cwd = ev.get("cwd") or d.get("cwd") or d.get("workdir") or os.getcwd()
    t = tool.lower().split("__")[-1]
    out = []
    cmds = []
    for k in SHELL_KEYS:
        v = d.get(k)
        if isinstance(v, list):
            v = " ".join(str(c) for c in v)
        if isinstance(v, str) and v.strip():
            cmds.append(v)
    if t in SHELL_TOOLS and not cmds:
        cmds = [" ".join(_strings(inp))]          # unknown shell shape: scan it all
    if t not in FILE_TOOLS:
        for c in cmds:
            out.append({"tool_name": "Bash", "tool_input": {"command": c}, "cwd": cwd})
    paths = _paths(inp)
    for s in _strings(inp):
        paths += PATCH_RX.findall(s)
    if t in READ_TOOLS:
        return out                       # a read is never a write, whatever its keys
    if t in FILE_TOOLS or paths:
        for p in paths:
            p = p.strip()
            full = os.path.expanduser(p)
            full = full if os.path.isabs(full) else os.path.join(cwd, full)
            out.append({"tool_name": "Write", "tool_input": {"file_path": full}, "cwd": cwd})
    return out


_GUARD_MOD = None


def _guard_mod():
    """The store guard's shell parser, reused so both guards read a command the
    same way (commit messages and heredoc bodies are data, not writes)."""
    global _GUARD_MOD
    if _GUARD_MOD is None:
        import importlib.util
        spec = importlib.util.spec_from_file_location("memory_write_guard", str(GUARD))
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        _GUARD_MOD = mod
    return _GUARD_MOD


RUNTIME_RX = re.compile(r"(?:^|/)(?:python[0-9.]*|node|perl|ruby|bash|sh|zsh|osascript|deno|bun)$")
# A segment that names a policy file is allowed only when its program is one of
# these plain readers (allowlist: anything else that names a policy file, from
# `rm` to `git checkout` to `python3 -c`, is refused).
READ_PROGRAMS = {"cat", "less", "more", "head", "tail", "grep", "egrep", "fgrep", "rg", "ag",
                 "ls", "wc", "diff", "cmp", "file", "stat", "shasum", "sha256sum", "md5",
                 "md5sum", "realpath", "readlink", "basename", "dirname", "echo", "printf",
                 "test", "[", "true", "jq", "column", "sort", "uniq", "cut", "nl", "bat"}
GIT_READ = {"log", "show", "diff", "status", "blame", "grep", "ls-files", "rev-parse",
            "cat-file", "describe", "branch", "remote", "config"}
PATHISH_RX = re.compile(r"""[~$\w./-]*[\w-]+\.(?:json|txt|toml|py|mjs|js|md|sh)\b|[~$\w./-]*/[\w./-]+""")


def _names_policy(text, cwd, roots):
    """Absolute, ~ or $HOME forms; a policy file's distinctive name; or any
    path-like substring (quoted code included) that resolves under a root."""
    if _mentions(text, roots) or "client-terms.txt" in text or "deny-patterns.txt" in text:
        return True
    for m in list(PATHISH_RX.finditer(text[:20000]))[:400]:
        tok = m.group(0).strip("'\"()")
        if not tok:
            continue
        full = os.path.expanduser(tok.replace("$HOME", str(HOME)))
        if not os.path.isabs(full):
            full = os.path.join(cwd, full)
        if _under(full, roots):
            return True
    return False


def _split(cmd):
    try:
        return _guard_mod().split_segments(_guard_mod().strip_shell_comments(cmd))
    except Exception:  # noqa: BLE001 — caller treats None as unparseable
        return None


def _words(seg):
    try:
        import shlex
        return shlex.split(seg)
    except ValueError:
        return seg.split()


def _segment_bases(segments, cwd):
    """The directory each segment runs in, following `cd` in command order."""
    here, out = cwd, []
    for seg in segments:
        out.append(here)
        w = _words(seg)
        if w and w[0] == "cd":
            tgt = os.path.expanduser(w[1]) if len(w) > 1 else str(HOME)
            here = tgt if os.path.isabs(tgt) else os.path.normpath(os.path.join(here, tgt))
    return out


def _is_plain_read(seg):
    w = [x for x in _words(seg) if "=" not in x.split("/", 1)[0]] or [""]
    prog = os.path.basename(w[0])
    if prog == "git":
        sub = next((x for x in w[1:] if not x.startswith("-")), "")
        return sub in GIT_READ and "--output" not in seg
    if prog == "jq" and any(x in ("-i", "--in-place") for x in w):
        return False
    return prog in READ_PROGRAMS


def _heredoc_into_runtime(raw):
    for line in raw.splitlines():
        if "<<" not in line:
            continue
        head = re.split(r"[;&|(]", line.split("<<", 1)[0])[-1].split()
        prog = next((x for x in head if "=" not in x), "")
        if RUNTIME_RX.search(prog):
            return True
    return False


def _deny_policy(norm, roots):
    if norm["tool_name"] == "Write":
        return _under(norm["tool_input"]["file_path"], roots)
    raw = norm["tool_input"]["command"]
    cwd = norm.get("cwd") or os.getcwd()
    if not _names_policy(raw, cwd, roots):
        return False
    g = _guard_mod()
    try:
        scannable = g.strip_heredocs(g.strip_commit_message(raw))
    except Exception:  # noqa: BLE001
        return True
    if _heredoc_into_runtime(raw) and not _names_policy(scannable, cwd, roots):
        return True                     # policy file named only inside a heredoc fed to a runtime
    segments = _split(scannable)
    if segments is None:
        return True                     # unparseable and names a policy file
    for seg, base in zip(segments, _segment_bases(segments, cwd)):
        if not _names_policy(seg, base, roots):
            continue
        s = NOT_A_WRITE.sub(" ", seg)
        if WRITE_SHAPE.search(s) or not _is_plain_read(seg):
            return True
    return False


def guard(raw, py=None, policy_only=False):
    """(allowed, reason).

    Store: delegated to hooks/memory-write-guard.py (reads stay allowed).
    Policy files: any write to them is denied.
    Fail closed whenever the call touches a protected path and the guard cannot
    decide (unparseable event, unknown mutating tool, guard missing, timeout,
    crash). Calls that touch nothing protected pass, so a broken guard never
    blocks ordinary work."""
    store = _store_paths()
    policy = policy_paths(include_code=not policy_only)
    protected = ([] if policy_only else store) + policy
    try:
        ev = json.loads(raw or "{}")
        if not isinstance(ev, dict):
            raise ValueError("event is not an object")
    except ValueError:
        if _mentions(raw or "", protected):
            return False, "memory guard: unparseable tool event that names a protected path"
        return True, ""
    tool, inp = _tool_and_input(ev)
    t = tool.lower().split("__")[-1]
    blob = "\n".join(_strings(inp))
    events = normalize_event(ev)
    cwd = ev.get("cwd") or os.getcwd()
    touches = _names_policy(blob, cwd, protected) or any(
        _under(n["tool_input"]["file_path"], protected)
        for n in events if n["tool_name"] == "Write")
    # The store guard also treats a bare MEMORY.md / QUARANTINE.md as the store.
    store_named = touches or "MEMORY.md" in blob or "QUARANTINE.md" in blob
    if not events and touches and t not in READ_TOOLS:
        return False, (f"memory guard: tool {tool!r} names a protected path and its "
                       "shape is not one the guard can read, so it is refused")
    for norm in events:
        if _deny_policy(norm, policy):
            return False, ("memory guard: this call would change the memory bridge's "
                           "policy (lane rules, client terms or a harness wiring file). "
                           "Those changes are the operator's; ask Craig.")
    if policy_only:
        return True, ""
    if not GUARD.exists():
        return (False, f"memory guard missing at {GUARD}; refusing a call that touches the store") \
            if touches else (True, "")
    if not store_named:
        return True, ""                  # nothing protected is named: no subprocess
    deadline = time.time() + GUARD_BUDGET_S
    for norm in events:
        try:
            left = deadline - time.time()
            if left <= 0:
                raise TimeoutError("guard budget spent")
            r = subprocess.run([py or sys.executable, str(GUARD)], input=json.dumps(norm),
                               capture_output=True, text=True, timeout=left)
        except Exception as e:  # noqa: BLE001 — timeout or spawn failure
            return False, f"memory guard could not decide ({e.__class__.__name__}); refused"
        if r.returncode == 2:
            return False, (r.stderr or "memory-write-guard denied this call").strip()
        if r.returncode != 0 and store_named:
            return False, "memory guard crashed on a call that touches the store; refused"
    return True, ""


