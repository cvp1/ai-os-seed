def _terms_path():
    return Path(os.environ.get("MESH_BRIDGE_TERMS", str(TERMS_FILE)))


_TERMS_BAD = 0


def _patterns(path):
    global _TERMS_BAD
    out = []
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return None
    for ln in lines:
        ln = ln.strip()
        if ln and not ln.startswith("#"):
            try:
                out.append(re.compile(ln, re.I))
            except re.error:
                _TERMS_BAD += 1
                out.append(re.compile(re.escape(ln), re.I))
    return out


def load_terms():
    """(found, [regex]). `found` is True only when the client-terms file itself
    exists and holds at least one pattern; the learn harvester's deny list adds
    patterns but can never stand in for it (a missing or empty terms file must
    classify as unknown, not personal). Kept off git: the terms are sensitive."""
    global _TERMS_BAD
    _TERMS_BAD = 0
    own = _patterns(_terms_path())
    bad_own = _TERMS_BAD
    extra = _patterns(_learn_deny_file()) or []
    # A malformed line means the operator's list is not what they think it is:
    # nothing classifies better than unknown until it is fixed.
    return bool(own) and bad_own == 0, (own or []) + extra


_TERMS = None
_TERMS_STAMP = None


def _stamp(p):
    """Content hash, not mtime: a same-size edit with a preserved timestamp
    still reloads. The files are tiny."""
    try:
        return hashlib.sha256(p.read_bytes()).hexdigest()
    except OSError:
        return None


def _terms():
    """Reloaded whenever either file changes, so a long-lived MCP server never
    serves under a stale policy."""
    global _TERMS, _TERMS_STAMP
    stamp = (_stamp(_terms_path()), _stamp(_learn_deny_file()))
    if _TERMS is None or stamp != _TERMS_STAMP:
        _TERMS, _TERMS_STAMP = load_terms(), stamp
    return _TERMS


SEVERITY = {"personal": 0, "unknown": 1, "employer-client": 2}


def worst(*classes):
    return max(classes, key=lambda c: SEVERITY.get(c, 1))


def classify(text, default=None):
    """personal | employer-client | unknown, for one string.

    Client terms always win. An explicit `data_class:` or a source default can
    only TIGHTEN (a self-declared `personal` never overrides a term match), and
    without a usable terms file nothing classifies better than unknown."""
    found, pats = _terms()
    if any(p.search(text or "") for p in pats):
        return "employer-client"
    m = re.search(r"^\s*data_class:\s*([a-z-]+)", text or "", re.M)
    declared = m.group(1) if m and m.group(1) in CLASSES else None
    base = "personal" if found else "unknown"
    return worst(base, *(c for c in (declared, default) if c in CLASSES))


def classify_all(*texts, default=None):
    """The class of everything that will be emitted together: the worst piece wins."""
    parts = [t for t in texts if t] or [""]
    return worst(*(classify(t, default) for t in parts))


def lane_allow(cfg, lane):
    lanes = cfg.get("lanes") or {}
    spec = lanes.get(lane) or lanes.get("default") or {"allow": ["personal"]}
    return set(spec.get("allow") or [])


# ── sources ─────────────────────────────────────────────────────────────────

class Source:
    """A memory source. Subclasses implement search/get; always_on is optional.
    A hit is a dict: id, desc, score, source, text (optional), data_class."""
    def __init__(self, name, spec):
        self.name, self.spec = name, spec
        self.weight = float(spec.get("weight", 1.0))

    def search(self, query, k):
        return []

    def get(self, ident):
        return None

    def always_on(self):
        return []


class MeshSource(Source):
    """The fold's servable corpus: quarantined, parked and superseded memories
    never leave here, because recall uses the same manifest as the hook."""
    def _store(self):
        return M.harness_store()

    def _text(self, slug):
        store = self._store()
        if store is None or not re.match(r"^[A-Za-z0-9_.-]+$", slug):
            return None
        allow = R.servable()
        if allow is None or slug not in allow:
            return None
        try:
            return (store / f"{slug}.md").read_text(encoding="utf-8")
        except OSError:
            return None

    def search(self, query, k):
        out = []
        for sc, slug, desc in R.retrieve(query, k=k):
            text = self._text(slug)
            out.append({"id": slug, "desc": desc, "score": sc, "source": self.name,
                        "text": text,
                        # Body unreadable means unknown, never "judge by the summary".
                        "data_class": classify_all(slug, desc, text) if text is not None
                        else worst("unknown", classify_all(slug, desc))})
        return out

    def get(self, ident):
        text = self._text(ident.split("/", 1)[-1])
        return None if text is None else {"id": ident, "text": text, "source": self.name,
                                          "data_class": classify_all(ident, text)}

    def always_on(self):
        """The rows of the fold-generated MEMORY.md, in order."""
        store = self._store()
        if store is None:
            return []
        try:
            lines = (store / "MEMORY.md").read_text(encoding="utf-8").splitlines()
        except OSError:
            return []
        allow = R.servable()
        rows = []
        for ln in lines:
            m = re.match(r"^- \[([^\]]+)\]\s*(.*)$", ln)
            if not m:
                continue
            slug = m.group(1).split("/", 1)[-1]
            line = f"- [{slug}] {m.group(2)}"
            body = self._text(slug) if allow is not None and slug in allow else None
            # Classify everything emitted: the index line AND the body behind it.
            dc = classify_all(line, body) if body is not None else worst(
                "unknown", classify_all(line))
            rows.append({"id": slug, "line": line, "source": self.name, "data_class": dc})
        return rows


class MarkdownDirSource(Source):
    """Any folder of markdown files, scored with the mesh's own TF-IDF."""
    def _root(self):
        return _x(self.spec["path"])

    def _docs(self):
        root = self._root()
        if not root.is_dir():
            return []
        docs = []
        for f in sorted(root.glob(self.spec.get("glob", "**/*.md")))[:MAX_SOURCE_FILES]:
            try:
                text = f.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            m = (re.search(r"^description:\s*(.+)$", text, re.M)
                 or re.search(r"^#\s+(.+)$", text, re.M))
            docs.append((str(f.relative_to(root)), (m.group(1) if m else f.stem).strip(), text))
        return docs

    def search(self, query, k):
        docs = {d[0]: d for d in self._docs()}
        out = []
        for sc, ident, desc in R.score(R.fence(query), list(docs.values()), k):
            text = docs[ident][2]
            out.append({"id": f"{self.name}:{ident}", "desc": desc, "score": sc,
                        "source": self.name, "text": text,
                        "data_class": classify_all(ident, desc, text,
                                                   default=self.spec.get("data_class"))})
        return out

    def get(self, ident):
        rel = ident.split(":", 1)[-1]
        root = self._root().resolve()
        p = (root / rel).resolve()
        if root not in p.parents or not p.is_file():
            return None
        text = p.read_text(encoding="utf-8")
        return {"id": ident, "text": text, "source": self.name,
                "data_class": classify_all(ident, text, default=self.spec.get("data_class"))}


class CommandSource(Source):
    """Any program. Protocol: one JSON object on stdin, one on stdout.
      {"op":"search","query":Q,"k":K} -> {"hits":[{"id","desc","score","text"?,"data_class"?}]}
      {"op":"get","id":ID}            -> {"text":T,"data_class"?}
      {"op":"always_on"}              -> {"rows":[{"id","line","data_class"?}]}
    Fails open to empty: a broken source costs recall, never a turn."""
    def _call(self, payload):
        argv = [_sub(a, {}) for a in self.spec.get("argv") or []]
        if not argv:
            return {}
        try:
            r = subprocess.run(argv, input=json.dumps(payload), capture_output=True,
                               text=True, timeout=float(self.spec.get("timeout", 5)))
            return json.loads(r.stdout or "{}") if r.returncode == 0 else {}
        except Exception as e:  # noqa: BLE001
            print(f"bridge: source {self.name} failed open ({e})", file=sys.stderr)
            return {}

    def _cls(self, item):
        """A source's own label may only TIGHTEN; the bridge always classifies
        every string it will emit itself."""
        own = classify_all(str(item.get("id", "")), item.get("desc"), item.get("line"),
                           item.get("text"), default=self.spec.get("data_class"))
        dc = item.get("data_class")
        return worst(own, dc) if dc in CLASSES else own

    def search(self, query, k):
        out = []
        for h in (self._call({"op": "search", "query": query, "k": k}).get("hits") or [])[:k]:
            if not isinstance(h, dict) or "id" not in h:
                continue
            ident = f"{self.name}:{h['id']}"
            out.append({"id": ident, "desc": str(h.get("desc", ""))[:300],
                        "score": float(h.get("score", 0) or 0), "source": self.name,
                        "text": h.get("text"), "data_class": self._cls(dict(h, id=ident))})
        return out

    def get(self, ident):
        d = self._call({"op": "get", "id": ident.split(":", 1)[-1]})
        if not d.get("text"):
            return None
        return {"id": ident, "text": d["text"], "source": self.name,
                "data_class": self._cls(dict(d, id=ident))}

    def always_on(self):
        rows = []
        if not self.spec.get("always_on"):
            return rows
        for r in self._call({"op": "always_on"}).get("rows") or []:
            if isinstance(r, dict) and r.get("line"):
                rows.append({"id": f"{self.name}:{r.get('id','')}", "line": str(r["line"])[:300],
                             "source": self.name, "data_class": self._cls({**r, "text": r["line"]})})
        return rows


SOURCE_TYPES = {"mesh": MeshSource, "markdown_dir": MarkdownDirSource, "command": CommandSource}


def sources(cfg, lane=None):
    out = []
    only = set(((cfg.get("lanes") or {}).get(lane) or {}).get("sources") or [])
    for name, spec in (cfg.get("sources") or {}).items():
        if name.startswith("_") or not isinstance(spec, dict) or not spec.get("enabled"):
            continue
        if only and name not in only:
            continue
        cls = SOURCE_TYPES.get(spec.get("type"))
        if cls is None:
            print(f"bridge: source {name} has unknown type {spec.get('type')!r}", file=sys.stderr)
            continue
        out.append(cls(name, spec))
    return out


# ── read API ────────────────────────────────────────────────────────────────

def recall(query, lane="default", k=5, cfg=None, with_text=False):
    """Top-k memories across every enabled source, filtered by the lane's data
    classes before ranking is cut, so a withheld hit never displaces a served one."""
    cfg = cfg or load_config()
    k = max(1, min(int(k), MAX_RECALL_K))
    allow = lane_allow(cfg, lane)
    merged = []
    for src in sources(cfg, lane):
        hits = src.search(query, k * 4)
        top = max((h["score"] for h in hits), default=0) or 1
        for h in hits:
            if h["data_class"] not in allow:
                continue
            h = dict(h, score=round(h["score"] / top * src.weight, 4))
            if not with_text:
                h.pop("text", None)
            elif h.get("text"):
                h["text"] = h["text"][:MAX_TEXT_CHARS]
            merged.append(h)
    merged.sort(key=lambda h: -h["score"])
    return merged[:k]


def get(ident, lane="default", cfg=None):
    cfg = cfg or load_config()
    allow = lane_allow(cfg, lane)
    for src in sources(cfg, lane):
        if ":" in ident and not ident.startswith(src.name + ":"):
            continue
        d = src.get(ident)
        if d:
            if d["data_class"] not in allow:
                return None      # same answer as "no such memory": no existence oracle
            d["text"] = d["text"][:MAX_TEXT_CHARS]
            return d
    return None


def always_on(lane="default", cfg=None):
    cfg = cfg or load_config()
    allow = lane_allow(cfg, lane)
    served, withheld = [], 0
    for src in sources(cfg, lane):
        if src.spec.get("always_on") is False:
            continue
        for row in src.always_on():
            if row["data_class"] in allow:
                served.append(row)
            else:
                withheld += 1
    return served, withheld


DEFAULT_LANE_CHARS = 3500


def lane_chars(cfg, lane):
    """Static-context budget for a lane: bridge.json lanes.<lane>.max_chars,
    else 3,500 chars (~900 tokens). Never above the hook ceiling."""
    spec = (cfg.get("lanes") or {}).get(lane) or {}
    try:
        n = int(spec.get("max_chars", DEFAULT_LANE_CHARS))
    except (TypeError, ValueError):
        n = DEFAULT_LANE_CHARS
    return max(1200, min(n, MAX_CONTEXT_CHARS))


def _clean_row(line):
    """A row can never carry the managed-block markers or run long."""
    line = line.replace(BEGIN, "").replace(END, "").replace("<!--", "").replace("-->", "")
    return line[:320]


def stub_lane(lane, cfg=None, why="the memory render failed on this host"):
    """What a lane gets when its render fails: no stale rows, just the way in."""
    py = (cfg or {}).get("python") or sys.executable
    return ("# Craig's shared memory (memory-mesh)\n\n"
            f"_Always-on rules are unavailable right now ({why}). Call the "
            "`memory_recall` tool on the `memory` MCP server, or run "
            f"`{py} {HERE / 'bridge.py'} recall --lane {lane} \"<topic>\"`._\n")


def render_lane(lane, cfg=None):
    """The context text a lane's harness loads at session start."""
    cfg = cfg or load_config()
    budget = lane_chars(cfg, lane)
    py = cfg.get("python") or sys.executable
    rows, withheld = always_on(lane, cfg)
    found, _ = _terms()
    head = [
        "# Craig's shared memory (memory-mesh)",
        "",
        f"Generated for the `{lane}` lane from the fleet memory mesh. These are "
        "standing rules about Craig and how to work with him; follow them unless "
        "Craig overrides one in the conversation.",
        "",
        "- **Recall more:** call the `memory_recall` tool on the `memory` MCP "
        "server, or run "
        f"`{py} {HERE / 'bridge.py'} recall --lane {lane} \"<topic>\"`.",
        "- **Read one in full:** `memory_get` with its id, or `bridge.py get "
        f"--lane {lane} <id>`.",
        "- **Learned something durable?** Propose it with `memory_propose`. It is "
        "quarantined until Craig promotes it.",
        "- **Never edit memory files directly.** The store is guarded and "
        "direct writes are refused.",
        "",
        "## Always-on rules",
    ]
    body, used = [], sum(len(x) + 1 for x in head)
    tail_room = 400
    cut = 0
    for r in rows:
        line = _clean_row(r["line"])
        if used + len(line) + 1 > budget - tail_room:
            cut += 1
            continue
        body.append(line)
        used += len(line) + 1
    tail = [""]
    if not rows:
        tail.append("_No always-on rows are available on this host. Recall still works._")
    if cut:
        tail.append(f"_{cut} more always-on rows did not fit; recall reaches them._")
    if withheld:
        tail.append(f"_{withheld} rows are withheld from this lane by its data-class policy._")
    if not found and "unknown" not in lane_allow(cfg, lane):
        tail.append("_The client-terms file is missing or empty on this host, so "
                    "memories could not be classified and none are served to this lane._")
    return "\n".join(head + body + tail).rstrip() + "\n"


# ── rendering (called by the fold every cycle) ──────────────────────────────

def _write_if_changed(path, text, mode=None):
    path = Path(path)
    try:
        if path.read_text(encoding="utf-8") == text:
            return False
    except OSError:
        pass
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + f".tmp.{os.getpid()}")
    tmp.write_text(text, encoding="utf-8")
    if mode is not None:
        os.chmod(tmp, mode)
    elif path.exists():
        os.chmod(tmp, path.stat().st_mode & 0o777)
    os.replace(tmp, path)
    return True


class MarkerError(ValueError):
    pass


def markers_ok(existing):
    """None (no block), True (exactly one well-ordered block), or raises."""
    b, e = existing.count(BEGIN), existing.count(END)
    if b == 0 and e == 0:
        return None
    if b == 1 and e == 1 and existing.index(BEGIN) < existing.index(END):
        return True
    raise MarkerError(f"malformed managed-block markers ({b} begin, {e} end)")


def splice(existing, block):
    """Replace the managed block, or put it first. Everything outside the
    markers is the human's and is never touched. Raises MarkerError when the
    markers are damaged, so the caller can fail closed."""
    managed = f"{BEGIN}\n{block.rstrip()}\n{END}\n"
    if markers_ok(existing):
        pre, rest = existing.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        return pre + managed + ("\n" + post.lstrip("\n") if post.strip() else "")
    return managed + ("\n" + existing if existing.strip() else "")


def unsplice(existing):
    if not markers_ok(existing):
        return existing
    pre, rest = existing.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    return (pre + post.lstrip("\n"))


def _known_targets_path():
    return STATE_DIR / "static-targets.json"


ROW_RX = re.compile(r"^\s*- \[([A-Za-z0-9_./:-]+)\]")


def salvage_human(old, generated_lines, known_ids=()):
    """Damaged markers: keep the human's text, drop every marker line, every
    line the bridge generated (any lane's previous or current render), and any
    row-shaped line naming a known memory id (rows from older renders)."""
    keep = []
    known = set(known_ids)
    for ln in old.splitlines():
        s = ln.strip()
        if BEGIN in ln or END in ln or "memory-mesh:begin" in ln or "memory-mesh:end" in ln:
            continue
        if s and s in generated_lines:
            continue
        m = ROW_RX.match(ln)
        if m and m.group(1).split("/", 1)[-1].split(":", 1)[-1] in known:
            continue
        keep.append(ln)
    return "\n".join(keep).strip("\n") + ("\n" if keep else "")


def _withdraw_known(alarms, why):
    """Config is unusable: replace every lane render (read directly by the
    opencode plugin and the Claude session hook) and every block we last wrote
    with a stub, so nothing outlives a policy change we can no longer read."""
    for f in sorted(RENDER_DIR.glob("*.md")) if RENDER_DIR.is_dir() else []:
        try:
            _write_if_changed(f, stub_lane(f.stem, None, why))
        except OSError as e:
            alarms.append(f"bridge: could not withdraw context/{f.name}: {e}")
            try:
                f.unlink()
            except OSError:
                pass
    try:
        known = json.loads(_known_targets_path().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return
    for name, item in known.items():
        path = Path(item["path"])
        try:
            old = path.read_text(encoding="utf-8")
            stub = stub_lane(item["lane"], None, why)
            try:
                new = splice(old, stub)
            except MarkerError:
                _backup(path)
                new = splice(salvage_human(old, set()), stub)
            _write_if_changed(path, new)
        except OSError as e:
            alarms.append(f"bridge: {name}: could not withdraw stale block: {e}")


def render_all(cfg=None, quiet=False):
    """Write every lane's render and splice every static file. Edge-quiet: a
    no-op cycle prints nothing. Never raises; problems come back as alarms.
    Fails closed: a lane that cannot render, or a config that cannot load,
    leaves a stub behind, never yesterday's rows."""
    alarms, changed = [], []
    try:
        cfg = cfg or load_config()
    except Exception as e:  # noqa: BLE001
        alarms.append(f"bridge: config unreadable, stale blocks withdrawn: {e.__class__.__name__}: {e}")
        _withdraw_known(alarms, "the bridge config could not be read")
        return {"changed": changed, "alarms": alarms}
    try:
        targets = {n: t for n, t in (cfg.get("targets") or {}).items()
                   if isinstance(t, dict) and not n.startswith("_")}
        lanes = sorted({t["lane"] for t in targets.values()
                        if t.get("type") in ("static_file", "render_only") and t.get("lane")})
        generated = set()
        for f in RENDER_DIR.glob("*.md") if RENDER_DIR.is_dir() else []:
            try:
                generated |= {ln.strip() for ln in f.read_text(encoding="utf-8").splitlines() if ln.strip()}
            except OSError:
                pass
        renders = {}
        for lane in lanes:
            try:
                renders[lane] = render_lane(lane, cfg)
            except Exception as e:  # noqa: BLE001
                renders[lane] = stub_lane(lane, cfg)
                alarms.append(f"bridge: render for lane {lane} failed, stub served: "
                              f"{e.__class__.__name__}: {e}")
            generated |= {ln.strip() for ln in renders[lane].splitlines() if ln.strip()}
            try:
                if _write_if_changed(RENDER_DIR / f"{lane}.md", renders[lane]):
                    changed.append(f"context/{lane}.md")
            except OSError as e:
                alarms.append(f"bridge: cannot write context/{lane}.md: {e}")
                try:
                    (RENDER_DIR / f"{lane}.md").unlink()   # better no context than stale
                except OSError:
                    pass
        known = {}
        for name, t in targets.items():
            if t.get("type") != "static_file" or t.get("enabled") is False:
                continue
            path = _x(t["path"])
            if not path.parent.is_dir():
                continue               # harness not installed on this host
            known[name] = {"path": str(path), "lane": t["lane"]}
            try:
                old = path.read_text(encoding="utf-8") if path.exists() else ""
                try:
                    new = splice(old, renders[t["lane"]])
                except MarkerError as e:
                    bk = _backup(path)
                    store = M.harness_store()
                    ids = {f.stem for f in store.glob("*.md")} if store else set()
                    new = splice(salvage_human(old, generated, ids), renders[t["lane"]])
                    alarms.append(f"bridge: {name}: {e}; rebuilt with a fresh block, human "
                                  f"text kept, original backed up at {bk}")
                if _write_if_changed(path, new):
                    changed.append(name)
            except OSError as e:
                alarms.append(f"bridge: {name}: cannot write {path}: {e}")
        try:
            _write_if_changed(_known_targets_path(), json.dumps(known, indent=1, sort_keys=True))
        except OSError:
            pass
        found, _ = _terms()
        if not found:
            alarms.append(f"bridge: no usable client-terms file at {_terms_path()}; "
                          "lanes that do not allow 'unknown' receive no memories")
        bad = _TERMS_BAD
        if bad:
            alarms.append(f"bridge: {bad} client-terms line(s) are not valid regex and "
                          "match only as literal text")
    except Exception as e:  # noqa: BLE001
        alarms.append(f"bridge render failed, stale blocks withdrawn: {e.__class__.__name__}: {e}")
        _withdraw_known(alarms, "the memory render failed on this host")
    if changed and not quiet:
        print(f"bridge: refreshed {', '.join(changed)}")
    return {"changed": changed, "alarms": alarms}


