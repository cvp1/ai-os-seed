def _template(name, cfg):
    py = cfg.get("python") or sys.executable
    b = str(HERE / "bridge.py")
    if name == "grok_hooks":
        return json.dumps({"hooks": {
            "PreToolUse": [{"hooks": [{"type": "command", "command": f"{py} {b} guard --harness grok",
                                       "timeout": 15}]}],
            "SessionStart": [{"hooks": [{"type": "command",
                                         "command": f"{py} {b} render --quiet", "timeout": 60}]}],
            "SessionEnd": [{"hooks": [{"type": "command",
                                       "command": f"{py} {HERE / 'learn_harvest.py'} --session-end",
                                       "timeout": 8}]}]}}, indent=2) + "\n"
    if name == "opencode_loader":
        return ("// memory-mesh: generated by bridge.py install; undo with bridge.py uninstall --apply\n"
                f"export {{ CCMemory }} from {json.dumps((HERE / 'opencode_memory_plugin.mjs').as_uri())};\n")
    raise KeyError(name)


def _claude_settings_plan(t):
    """(path, old, new) for the user-global settings and each project file."""
    plans = []
    user = _x(t["path"])
    old = user.read_text(encoding="utf-8") if user.exists() else "{}\n"
    doc = json.loads(old)
    hooks = doc.setdefault("hooks", {})
    # The recall hook moves to user scope verbatim (fold_watch matches the string).
    recall_cmd = None
    for pp in t.get("project_settings") or []:
        p = _x(pp)
        if not p.exists():
            continue
        pold = p.read_text(encoding="utf-8")
        pdoc = json.loads(pold)
        ups = (pdoc.get("hooks") or {}).get("UserPromptSubmit") or []
        keep = []
        for e in ups:
            cmds = [h.get("command", "") for h in e.get("hooks", [])]
            if any("memory-mesh/retrieve.py" in c for c in cmds):
                recall_cmd = recall_cmd or next(c for c in cmds if "memory-mesh/retrieve.py" in c)
                continue
            keep.append(e)
        if len(keep) != len(ups):
            if keep:
                pdoc["hooks"]["UserPromptSubmit"] = keep
            else:
                del pdoc["hooks"]["UserPromptSubmit"]
            plans.append((p, pold, json.dumps(pdoc, indent=2, ensure_ascii=False) + "\n"))
    recall_cmd = recall_cmd or f"{HOME}/.venvs/aios-seed/bin/python3 {RETRIEVE_PY}"
    ups = hooks.setdefault("UserPromptSubmit", [])
    if not any("memory-mesh/retrieve.py" in h.get("command", "") for e in ups for h in e.get("hooks", [])):
        ups.append({"hooks": [{"type": "command", "command": recall_cmd}]})
    ss = hooks.setdefault("SessionStart", [])
    if not any("bridge.py hook claude-session" in h.get("command", "") for e in ss for h in e.get("hooks", [])):
        py = "/usr/bin/python3"
        ss.append({"matcher": "startup|resume|clear|compact",
                   "hooks": [{"type": "command",
                              "command": f"{py} {HERE / 'bridge.py'} hook claude-session",
                              "timeout": 10}]})
    # Policy guard: Claude Code guards the store itself; this adds the bridge's
    # policy files (lane rules, client terms, harness wiring) for Claude too.
    pre = hooks.setdefault("PreToolUse", [])
    pre[:] = [e for e in pre if not any("bridge.py guard" in h.get("command", "")
                                        for h in e.get("hooks", []))]
    if True:
        pre.append({"matcher": "Write|Edit|MultiEdit|NotebookEdit|Bash|mcp__.*",
                    "hooks": [{"type": "command",
                               "command": f"/usr/bin/python3 {HERE / 'bridge.py'} guard "
                                          "--harness claude --policy-only",
                               "timeout": 15}]})
    plans.insert(0, (user, old, json.dumps(doc, indent=2, ensure_ascii=False) + "\n"))
    return plans


def _claude_settings_unplan(t):
    user = _x(t["path"])
    if not user.exists():
        return []
    old = user.read_text(encoding="utf-8")
    doc = json.loads(old)
    changed = False
    for event, marker in (("SessionStart", "bridge.py hook claude-session"),
                          ("PreToolUse", "bridge.py guard")):
        ents = (doc.get("hooks") or {}).get(event) or []
        keep = [e for e in ents if not any(marker in h.get("command", "")
                                           for h in e.get("hooks", []))]
        if len(keep) != len(ents):
            changed = True
            if keep:
                doc["hooks"][event] = keep
            else:
                del doc["hooks"][event]
    if not changed:
        return []
    # The recall hook stays in user scope: it predates the bridge's SessionStart.
    return [(user, old, json.dumps(doc, indent=2, ensure_ascii=False) + "\n")]


def plan_target(name, t, cfg, undo=False):
    """Return a list of (path, old, new) file edits, or a ('cmd', argv) action."""
    typ = t.get("type")
    if typ in ("static_file",):
        p = _x(t["path"])
        if not p.parent.is_dir() or not p.exists():
            return []
        old = p.read_text(encoding="utf-8")
        new = unsplice(old) if undo else splice(old, render_lane(t["lane"], cfg))
        return [(p, old, new)] if new != old else []
    if typ == "mcp_toml":
        p = _x(t["path"])
        if not p.exists():
            return []
        old = p.read_text(encoding="utf-8")
        base = _strip_toml(old)
        if not undo and re.search(r"^\[mcp_servers\.memory\]", base, re.M):
            print(f"bridge: {name}: {p} already declares [mcp_servers.memory] outside the managed block; left alone",
                  file=sys.stderr)
            return []
        new = base if undo else base.rstrip("\n") + "\n\n" + _toml_block(cfg, t["lane"])
        return [(p, old, new)] if new != old else []
    if typ == "mcp_opencode":
        p = _x(t["path"])
        if not p.exists():
            return []
        old = p.read_text(encoding="utf-8")
        doc = json.loads(old)
        entry = {"type": "local", "enabled": True,
                 "command": [cfg.get("python") or sys.executable, str(MCP_SERVER),
                             "--lane", t["lane"]]}
        inline = '"mcp": {\n    "memory": ' + json.dumps(entry) + "\n  }"
        if undo:
            new = old.replace(inline, '"mcp": {}')
            if new == old and "memory" in (doc.get("mcp") or {}):
                doc["mcp"].pop("memory")
                new = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
        elif (doc.get("mcp") or {}).get("memory") == entry:
            return []
        elif (doc.get("mcp") or {}).get("memory") and \
                json.dumps(doc["mcp"]["memory"]) in old:
            new = old.replace(json.dumps(doc["mcp"]["memory"]), json.dumps(entry), 1)
        elif re.search(r'"mcp":\s*\{\s*\}', old):
            # Minimal text edit: the human's formatting elsewhere is untouched.
            new = re.sub(r'"mcp":\s*\{\s*\}', lambda _m: inline, old, count=1)
        else:
            doc.setdefault("mcp", {})["memory"] = entry
            new = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
        json.loads(new)                       # never write invalid JSON
        return [(p, old, new)] if new != old else []
    if typ == "claude_settings":
        plans = _claude_settings_unplan(t) if undo else _claude_settings_plan(t)
        return [(p, o, n) for p, o, n in plans if o != n]
    if typ in ("json_file", "text_file"):
        p = _x(t["path"])
        if not p.parent.parent.is_dir():
            return []
        old = p.read_text(encoding="utf-8") if p.exists() else ""
        if undo:
            return [(p, old, None)] if old and "memory-mesh" in old else []
        new = _template(t["template"], cfg)
        return [(p, old, new)] if new != old else []
    if typ == "mcp_cli":
        argv0 = _x(_sub(t["probe"][0], cfg))
        exe_ok = argv0.exists() and all(_x(_sub(a, cfg)).exists() for a in t["probe"][1:2]
                                         if a.endswith(".py"))
        if not exe_ok:
            return []
        probe = subprocess.run([_sub(a, cfg) for a in t["probe"]], capture_output=True,
                               text=True, timeout=60)
        present = probe.returncode == 0
        if undo:
            return [("cmd", [_sub(a, cfg) for a in t["remove"]])] if present else []
        return [] if present else [("cmd", [_sub(a, cfg) for a in t["add"]])]
    return []


def install(apply=False, undo=False, only=None, cfg=None):
    cfg = cfg or load_config()
    report = []
    for name, t in (cfg.get("targets") or {}).items():
        if name.startswith("_") or not isinstance(t, dict) or t.get("enabled") is False:
            continue
        if only and name not in only:
            continue
        try:
            plans = plan_target(name, t, cfg, undo=undo)
        except Exception as e:  # noqa: BLE001
            report.append((name, "ERROR", f"{e.__class__.__name__}: {e}"))
            continue
        if not plans:
            report.append((name, "ok", "nothing to change"))
            continue
        for plan in plans:
            if plan[0] == "cmd":
                argv = plan[1]
                if apply:
                    r = subprocess.run(argv, capture_output=True, text=True, timeout=120)
                    report.append((name, "ran" if r.returncode == 0 else "FAILED",
                                   " ".join(argv) + ("" if r.returncode == 0 else
                                                     f" -> {(r.stderr or r.stdout).strip()[-200:]}")))
                else:
                    report.append((name, "would run", " ".join(argv)))
                continue
            path, old, new = plan
            label = str(path).replace(str(HOME), "~")
            if new is None:
                if apply:
                    _backup(path)
                    path.unlink()
                report.append((name, "removed" if apply else "would remove", label))
                continue
            if apply:
                bk = _backup(path)
                _write_if_changed(path, new)
                report.append((name, "written", f"{label}" + (f" (backup {bk.name})" if bk else "")))
            else:
                report.append((name, "would write", label + "\n" + _diff(old, new, label)))
    return report


def status(cfg=None):
    cfg = cfg or load_config()
    rows = []
    for name, t in (cfg.get("targets") or {}).items():
        if name.startswith("_") or not isinstance(t, dict):
            continue
        typ = t.get("type")
        state = "?"
        try:
            if typ == "render_only":
                p = RENDER_DIR / f"{t['lane']}.md"
                state = "ok" if p.exists() else "MISSING render"
            elif typ == "static_file":
                p = _x(t["path"])
                state = ("no harness" if not p.parent.is_dir() else
                         "ok" if p.exists() and BEGIN in p.read_text(encoding="utf-8") else "NOT WIRED")
            else:
                pending = plan_target(name, t, cfg)
                state = "ok" if not pending else "NOT WIRED"
                if typ in ("mcp_cli", "json_file", "text_file", "mcp_toml", "mcp_opencode") and not pending:
                    p = t.get("path")
                    if p and not _x(p).exists() and typ != "mcp_cli":
                        state = "no harness"
        except Exception as e:  # noqa: BLE001
            state = f"ERROR {e.__class__.__name__}: {e}"
        rows.append((name, typ, t.get("lane", "-"), state))
    return rows


