#!/usr/bin/env python3
"""bridge: one memory, every model.

The memory mesh is model-agnostic underneath (plain files, stdlib Python). This
module is the one door every harness uses to reach it, whoever orchestrates:

  sources   where memories come from. `mesh` (the fold's servable corpus) is
            the default; `markdown_dir` and `command` plug in anything else.
  lanes     which data classes a model family may receive (bridge.json).
  targets   how a harness is wired: a static context file, an MCP server
            registration, a hook file, a plugin loader.

    bridge.py recall --lane codex "query"     top memories for a query (any process)
    bridge.py get --lane codex <id>           one memory's full text
    bridge.py index --lane grok               the always-on rules for a lane
    bridge.py propose --lane grok --hook H --rule R   quarantined candidate
    bridge.py render                          refresh every lane's context (the fold calls this)
    bridge.py guard --harness grok            PreToolUse store guard for any harness
    bridge.py hook claude-session             SessionStart context outside generated folders
    bridge.py install [--apply]               wire every target (dry run by default)
    bridge.py uninstall [--apply]             unwire every target
    bridge.py status                          what is wired, what is missing

Stdlib only, Python 3.9+. Reads never mutate the store. Writes from any model
go through memory_write.py as contains-untrusted and serve only after the
operator promotes them.
"""
